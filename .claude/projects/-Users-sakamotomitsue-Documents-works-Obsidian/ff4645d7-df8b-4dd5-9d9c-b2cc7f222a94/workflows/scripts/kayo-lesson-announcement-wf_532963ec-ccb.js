phase('Draft')
const ANGLES = [
  { key: 'promise', prompt: '角度A：「約束を果たしに来た手紙」。1通目の「形になりましたら、いちばんにご案内させてください」を回収することを手紙の芯にする。かよさまの言葉がレッスンを生んだ、という事実を静かに伝える。' },
  { key: 'room', prompt: '角度B：「あの部屋の続きの手紙」。体験セッションでかよさまが見た祭壇の間が、いまもMieyのパソコンの中にあり、それをかよさまの手元へお引っ越しできる——という一つの情景で手紙全体を貫く。物語の続きとして読ませる。' },
  { key: 'plain', prompt: '角度C：「静かで実務的な手紙」。詩情は最小限にし、何ができるか・何話か・何が要るか・急がなくていいことを、かよさまが判断しやすい形で率直に並べる。ただし文体はMieyの静かな声のまま。' },
]

const DRAFT_SCHEMA = {
  type: 'object',
  properties: {
    letter: { type: 'string', description: 'Cafetalkメッセージにそのまま貼れる完成本文（プレーンテキスト・署名Mieyまで）' },
    rationale: { type: 'string', description: 'この構成にした理由（3行以内）' },
  },
  required: ['letter', 'rationale'],
}

const JUDGE_SCHEMA = {
  type: 'object',
  properties: {
    scores: {
      type: 'object',
      properties: {
        voice: { type: 'number', description: '1通目と同じMieyの声か（1-10）' },
        promise: { type: 'number', description: '1通目の約束の回収と情報の正確さ（1-10）' },
        pressure: { type: 'number', description: '押しつけがましくないか。高いほど圧がない（1-10）' },
        action: { type: 'number', description: 'かよさまが次の一歩を判断できるか（1-10）' },
      },
      required: ['voice', 'promise', 'pressure', 'action'],
    },
    best_lines: { type: 'array', items: { type: 'string' }, description: 'この案から必ず残したい一文（最大3つ）' },
    problems: { type: 'array', items: { type: 'string' }, description: '削るべき・直すべき箇所' },
  },
  required: ['scores', 'best_lines', 'problems'],
}

const drafts = await parallel(ANGLES.map(a => () =>
  agent(`${CTX}\n\n# あなたの仕事\n${a.prompt}\n\nCafetalkのメッセージ欄にそのまま貼れる完成した手紙を書いてください。冒頭は「かよさま」から、末尾は「Miey」で終える。長さは1通目と同程度（30〜45行程度）を目安に。上記の制約をすべて守ること。`,
    { label: `draft:${a.key}`, phase: 'Draft', schema: DRAFT_SCHEMA })
    .then(r => r && ({ ...r, key: a.key }))
))

const alive = drafts.filter(Boolean)
log(`草案 ${alive.length}件 → 判定へ`)

phase('Judge')
const judged = await parallel(alive.map(d => () =>
  agent(`${CTX}\n\n# 判定対象の手紙（案${d.key}）\n---\n${d.letter}\n---\n\n# あなたの仕事\nこの手紙を、Mieyの立場（送る側）とかよさまの立場（受け取る側）の両方から厳しく採点してください。特に、(1)1通目と声が一致しているか、(2)事実の誤り（かよさまは体験受講済み＝第1話を飛ばして全3話、という点を間違えていないか。金額や外部サイトに触れていないか）、(3)売り込みの圧が出ていないか、(4)かよさまが「次に何をすればいいか」分かるか。採点は辛口に。`,
    { label: `judge:${d.key}`, phase: 'Judge', schema: JUDGE_SCHEMA })
    .then(v => v && ({ key: d.key, letter: d.letter, rationale: d.rationale, ...v,
      total: v.scores.voice + v.scores.promise + v.scores.pressure + v.scores.action }))
))

const ranked = judged.filter(Boolean).sort((a, b) => b.total - a.total)
return { ranked }